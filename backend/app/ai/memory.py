from app.ai.manager import AIManager
from app.utils.utils import extract_json

class MemoryExtractor:
    def __init__(self):
        self.ai = AIManager()
        
    def extract(self, message: str) -> list[str]:
        prompt = f"""
        Ты анализируешь сообщение пользователя.

        Твоя задача —
        создать готовые предложения,
        которые будут храниться
        в долговременной памяти.

        Каждый факт должен быть
        полным законченным предложением.

        НЕ пиши отдельные слова.

        НЕ пиши ключевые слова.

        НЕ сокращай.

        Пиши так,
        как будто через год другой AI
        прочитает эту память
        без контекста.
        
        Возвращай ТОЛЬКО JSON.

        Формат:

        [
            {{
                "content": "...",
                "save": true
            }}
        ]

        Правила.

        Сохранять только то,
        что останется актуальным
        через несколько месяцев.

        Можно сохранять:

        - имя
        - возраст
        - город
        - профессию
        - образование
        - языки
        - навыки
        - любимые книги
        - любимые фильмы
        - любимые игры
        - любимую музыку
        - любимые блюда
        - увлечения
        - хобби
        - домашних животных
        - семью
        - предпочтения
        - цели
        - привычки

        НЕ сохранять:

        - настроение
        - эмоции
        - планы на сегодня
        - вопросы
        - приветствия
        - шутки
        - временные состояния
        - предположения
        - комментарии
        - свои объяснения

        Если факт сомнительный —
        поставь

        "save": false

        Если сохранять нечего —

        []

        Сообщение:

        {message}
        """
        
        answer = self.ai.generate([
            {
                'role': 'user',
                'content': prompt
            }
        ])
        
        print(answer)
        
        data = extract_json(answer)
        if not isinstance(data, list):
            return []
        
        return data