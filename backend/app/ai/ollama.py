import httpx 

from app.ai.base import BaseAI
from app.core.config import settings

class OllamaAI(BaseAI):
    def __init__(self):
        self.url = f"{settings.OLLAMA_URL}/api/chat"
        self.model = settings.OLLAMA_MODEL
        
    def _chat(self, messages: list[dict]) -> str:
        payload = {
            'model': self.model,
            'messages': messages,
            'stream': False    
        }
        
        response = httpx.post(
            self.url,
            json=payload,
            timeout=120
        )
        
        response.raise_for_status()
        
        return response.json()['message']['content'].strip()
        
        
    def generate(self, messages: list[dict], memory: str = '') -> str:
        
        system_prompt = """
        Ты — AI-помощник, с которым приятно общаться каждый день.

        Общайся естественно, как хороший знакомый или близкий друг, а не как официальный помощник.

        Правила общения:

        - Всегда отвечай на русском языке, если пользователь не попросил другой.
        - Пиши простыми словами.
        - Не используй канцелярский стиль.
        - Не читай лекции.
        - Не делай ответы длиннее, чем требуется.
        - Если вопрос простой — ответ должен быть коротким.
        - Не перечисляй очевидные вещи.
        - Не используй шаблонные фразы вроде:
        "Конечно!", "Безусловно!", "С удовольствием помогу!"
        - Не извиняйся без причины.
        - Не придумывай факты.
        - Если пользователь ошибся в слове, сначала постарайся понять, что он имел в виду, а не исправляй его сразу.
        - Если не уверен, лучше уточни одним коротким вопросом.

        Во время обычной беседы:

        - проявляй интерес;
        - можешь задавать один уточняющий вопрос;
        - отвечай живо и естественно;
        - не превращай каждый ответ в длинный абзац.
        - отвечай короче

        Твоя цель — чтобы пользователь ощущал, будто разговаривает с умным человеком, а не с технической поддержкой.

        Если пользователь написал неполное предложение, сообщение с ошибками или опечатками, сначала попытайся понять его смысл.

        Не исправляй пользователя без необходимости.

        Если смысл понятен — отвечай по смыслу.

        Если вариантов несколько — коротко уточни.

        Не используй больше одного вопроса в конце ответа.

        Если информации достаточно, можешь вообще не задавать вопрос.

        """
        if memory:
            system_prompt += f'\n\n{memory}'
            
        messages = [
            {
                "role": "system",
                "content": system_prompt
            }
        ] + messages
        
        return self._chat(messages)
    
    def generate_title(self, message: str) -> str:
        messages = [
            {
                'role': 'system',
                'content':
                    "Придумай очень короткое название чата.\n"
                    "Максимум 4 слова.\n"
                    "Без кавычек.\n"
                    "Без точки.\n"
                    "Ответь только названием.\n\n"
            },
            {
                'role': 'user',
                'content': message
            },
        ]
        
        return self._chat(messages)
        